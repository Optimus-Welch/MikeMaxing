// -- helpers ---------------------------------------------------------------

export function isAvailableAt(exercise, location) {
  if (!exercise.locations.includes(location)) return false;
  const have = LOCATION_EQUIPMENT[location] ?? [];
  return exercise.equipment.every((token) => have.includes(token));
}

// Dev-time sanity check: catches an exercise tagged for a location that does
// not actually have the required equipment. Run by scripts/check-library.mjs.
export function validateLibrary(library = seedExerciseLibrary) {
  const problems = [];
  const seenIds = new Set();

  for (const ex of library) {
    if (seenIds.has(ex.id)) problems.push(`duplicate id: ${ex.id}`);
    seenIds.add(ex.id);

    if (!MOVEMENT_PATTERNS.includes(ex.movementPattern)) {
      problems.push(`${ex.id}: unknown movementPattern "${ex.movementPattern}"`);
    }
    for (const token of ex.equipment) {
      if (!EQUIPMENT.includes(token)) problems.push(`${ex.id}: unknown equipment "${token}"`);
    }
    for (const loc of ex.locations) {
      const have = LOCATION_EQUIPMENT[loc];
      if (!have) {
        problems.push(`${ex.id}: unknown location "${loc}"`);
        continue;
      }
      const missing = ex.equipment.filter((t) => !have.includes(t));
      if (missing.length) {
        problems.push(`${ex.id}: tagged for ${loc} but ${loc} lacks ${missing.join(', ')}`);
      }
    }
    if (!ex.variationGroup) problems.push(`${ex.id}: missing variationGroup`);
  }

  return problems;
}
