// The shipped exercise library — reference data, not user data.
//
// Schema per exercise:
//   id                unique slug
//   name              display name
//   movementPattern   one of MOVEMENT_PATTERNS
//   primaryMuscles    muscles doing most of the work
//   secondaryMuscles  meaningfully involved, but not the point of the lift
//   equipment         tokens from EQUIPMENT; a location must have ALL of them
//   locations         where this is actually worth doing ("Work" / "Home")
//   variationGroup    close variants share a group so freshness can rotate
//                     between families rather than between near-identical lifts
//   tier              'primary'   — heavy compound, goes first
//                     'secondary' — compound accessory
//                     'accessory' — isolation / low-skill finisher
//   capFriendly       true when the lift stays genuinely hard under Home's
//                     load caps (see LOCATION_LOAD_CAPS)
//   capStrategy       WHY it stays hard: 'unilateral' | 'tempo' | 'highRep' |
//                     'elevatedRange'. Null for lifts that simply don't need
//                     much load, or that aren't cap-limited at all.
//   loadNotes         free text, shown in the UI when a weight cap is relevant
//
// `capFriendly` / `capStrategy` exist so the generator can prefer the right
// Home variations from DATA rather than the UI hardcoding "if Home and squat
// then ...". Adding a new cap-beating variation is a data edit, not a code
// change.

